CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY CHECK(version = 1));
INSERT OR IGNORE INTO schema_version VALUES(1);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, username TEXT NOT NULL COLLATE NOCASE UNIQUE,
 password BLOB NOT NULL, owner INTEGER NOT NULL DEFAULT 0 CHECK(owner IN(0,1)),
 group_optin INTEGER NOT NULL DEFAULT 0 CHECK(group_optin IN(0,1)),
 CHECK(length(username) BETWEEN 2 AND 40)
);
CREATE TABLE IF NOT EXISTS sessions (
 token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS invites (
 token TEXT PRIMARY KEY, expires INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0 CHECK(used IN(0,1))
);
CREATE TABLE IF NOT EXISTS feeds (
 id INTEGER PRIMARY KEY, url TEXT NOT NULL UNIQUE, title TEXT NOT NULL,
 etag TEXT NOT NULL DEFAULT '', modified TEXT NOT NULL DEFAULT '',
 checked INTEGER NOT NULL DEFAULT 0, error TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS subscriptions (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 feed_id INTEGER NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
 category TEXT NOT NULL DEFAULT 'General' CHECK(length(category) BETWEEN 1 AND 40),
 PRIMARY KEY(user_id,feed_id)
);
CREATE TABLE IF NOT EXISTS group_feeds (
 feed_id INTEGER PRIMARY KEY REFERENCES feeds(id) ON DELETE CASCADE,
 category TEXT NOT NULL DEFAULT 'General' CHECK(length(category) BETWEEN 1 AND 40)
);
CREATE TABLE IF NOT EXISTS entries (
 id INTEGER PRIMARY KEY, feed_id INTEGER NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
 key TEXT NOT NULL, title TEXT NOT NULL, url TEXT NOT NULL, body TEXT NOT NULL,
 published INTEGER NOT NULL, UNIQUE(feed_id,key)
);
CREATE INDEX IF NOT EXISTS entries_date ON entries(published DESC,id DESC);
CREATE TABLE IF NOT EXISTS states (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 entry_id INTEGER NOT NULL REFERENCES entries(id) ON DELETE CASCADE,
 read INTEGER NOT NULL DEFAULT 0 CHECK(read IN(0,1)),
 saved INTEGER NOT NULL DEFAULT 0 CHECK(saved IN(0,1)),
 PRIMARY KEY(user_id,entry_id)
);
CREATE TABLE IF NOT EXISTS subscription_tags (
 user_id INTEGER NOT NULL, feed_id INTEGER NOT NULL,
 tag TEXT NOT NULL CHECK(length(tag) BETWEEN 1 AND 40),
 PRIMARY KEY(user_id,feed_id,tag),
 FOREIGN KEY(user_id,feed_id) REFERENCES subscriptions(user_id,feed_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS household_tags (
 feed_id INTEGER NOT NULL REFERENCES group_feeds(feed_id) ON DELETE CASCADE,
 tag TEXT NOT NULL CHECK(length(tag) BETWEEN 1 AND 40),
 PRIMARY KEY(feed_id,tag)
);
CREATE TABLE IF NOT EXISTS feed_groups (
 id INTEGER PRIMARY KEY,
 user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 60),
 tag TEXT NOT NULL DEFAULT '' CHECK(length(tag)<=40),
 UNIQUE(user_id,name)
);
CREATE UNIQUE INDEX IF NOT EXISTS household_group_names ON feed_groups(name) WHERE user_id IS NULL;
CREATE TABLE IF NOT EXISTS feed_group_members (
 group_id INTEGER NOT NULL REFERENCES feed_groups(id) ON DELETE CASCADE,
 feed_id INTEGER NOT NULL REFERENCES feeds(id) ON DELETE CASCADE,
 PRIMARY KEY(group_id,feed_id)
);
CREATE TABLE IF NOT EXISTS site_palette (
 id INTEGER PRIMARY KEY CHECK(id=1),
 palette TEXT NOT NULL DEFAULT '' CHECK(length(palette)<=40)
);
